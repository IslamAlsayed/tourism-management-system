foreach ($langs as $code => $translations) {
    $dir = $basePath . '/' . $code;
    if (!is_dir($dir)) {
        mkdir($dir, 0755, true);
    }
    
    $file = $dir . '/tourism.php';
    
    // Merge if exists
    $existing = [];
    if (file_exists($file)) {
        $existing = include $file;
        if (!is_array($existing)) $existing = [];
    }
    
    $merged = array_merge($existing, $translations);
    
    $export = var_export($merged, true);
    // clean up formatting for short array syntax
    $export = str_replace(array('array (', ')'), array('[', ']'), $export);
    
    $content = "<?php\n\nreturn " . $export . ";\n";
    
    file_put_contents($file, $content);
    echo "Wrote translations for [$code] to $file\n";
}

echo "Done.\n";
