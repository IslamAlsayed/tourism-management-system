function exportArrayToPhpSafeHelper($array, $indent = 1) {
    $spaces = str_repeat("    ", $indent);
    $content = "[\n";
    foreach ($array as $key => $value) {
        $safeKey = addcslashes((string)$key, "'\\");
        if (is_array($value)) {
            $content .= $spaces . "'$safeKey' => " . exportArrayToPhpSafeHelper($value, $indent + 1) . ",\n";
        } else {
            $safeValue = addcslashes((string)$value, "'\\");
            $content .= $spaces . "'$safeKey' => '$safeValue',\n";
        }
    }
    $content .= str_repeat("    ", $indent - 1) . "]";
    return $content;
}

function exportArrayToPhpSafe($array) {
    return "<?php\n\nreturn " . exportArrayToPhpSafeHelper($array) . ";\n";
}

$totalApplied = 0;

foreach ($translations as $file => $newData) {
    $targetFile = $basePath . '/' . $file;
    if (file_exists($targetFile)) {
        $existingData = include $targetFile;
        $modified = false;
        
        foreach ($newData as $key => $translatedValue) {
            if (isset($existingData[$key])) {
                $existingData[$key] = $translatedValue;
                $totalApplied++;
                $modified = true;
            }
        }
        
        if ($modified) {
            ksort($existingData);
            file_put_contents($targetFile, exportArrayToPhpSafe($existingData));
            echo "-> $file: Updated with translated values.\n";
        }
    }
}

