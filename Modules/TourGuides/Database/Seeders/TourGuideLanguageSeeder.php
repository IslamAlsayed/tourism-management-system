        if (empty($tourGuideIds)) {
            $this->command->warn('No tour guides found. Skipping language seeding.');
            return;
        }

        $insertData = [];
        $now = now();

        foreach ($guide_languages as $key => $lang) {
            // Skip if tour guide doesn't exist
            if (!isset($tourGuideIds[$key])) {
                continue;
            }

            $languages = explode('،', $lang);
            foreach ($languages as $language) {
                $languageName = strtolower(trim($language));
                if (isset($languagesCache[$languageName])) {
                    $insertData[] = [
                        'tour_guide_id' => $tourGuideIds[$key],
                        'language_id' => $languagesCache[$languageName]->id,
                        'created_at' => $now,
                        'updated_at' => $now,
                        'uuid' => (string) Str::uuid(),
                    ];
                }
            }
        }

        // Bulk insert in chunks for better performance
        if (!empty($insertData)) {
            foreach (array_chunk($insertData, 500) as $chunk) {
                TourGuideLanguage::insert($chunk);
            }
